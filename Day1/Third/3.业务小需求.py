CuName = input("请输入客户名称：")
SinPay = float(input("请输入单笔付款："))
PayCount = int(input("请输入付款笔数："))
PaySum = SinPay * PayCount
print("客户名称：",CuName)
print("单笔付款金额：",SinPay)
print("付款笔数：",PayCount)
