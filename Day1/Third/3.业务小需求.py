# 假设公司收到一批客户付款。
#
# 输入：
#
# 客户名称
# 单笔付款金额
# 付款笔数
#
# 计算：
#
# 付款总额 = 单笔付款金额 × 付款笔数
#
# 例如：
#
# 客户名称：贵州XX有限公司
# 单笔付款金额：1250.5
# 付款笔数：8
#
# 你的程序需要自己算出总金额并输出业务摘要。
